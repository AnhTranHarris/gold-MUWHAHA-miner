"""Frozen-155 original entry P5 -> conditional actual-original R9 hold/exit landmark.

Four June-Sep train-past / test-next folds. Source-ordinal snapshots generated by
continuation_landmarks.py; no full raw Coinexx quote reload for model fitting.
The model targets original-policy incremental cash, NOT a counterfactual trade.
"""
from __future__ import annotations
import argparse, json
from pathlib import Path
import numpy as np
from sklearn.linear_model import Ridge
from sklearn.metrics import roc_auc_score, mean_absolute_error

FEATURE_NAMES=['cash_now','stop_distance_cents','spread','spread_delta','MFE_cash','MAE_cash',
               'signed_recent_quote_mid_move','realized_quote_noise','observed_updates_1s',
               'recent_quote_efficiency','quote_gap_ms','M5_ATR','R9_S1_eff','entry_spread',
               'session','side','rearm','frozen_p5_original_direction']


def load_cache(cache:Path):
    data={}
    for m in range(5,10):
        data[m]={}
        for age in (1,3):
            with np.load(cache/f'landmark_{m:02d}_{age}s.npz',allow_pickle=False) as z:
                data[m][age]={k:z[k] for k in z.files}
                d=data[m][age]
                if d['X'].shape!=(len(d['delta']),len(FEATURE_NAMES)):
                    raise ValueError('Wrong original 1/3 sec feature contract')
                if not (np.all(np.diff(d['entry_ordinal'])>0) and
                        np.all(d['source_ordinal']>d['entry_ordinal']) and
                        np.all(np.isfinite(d['X']))):
                    raise ValueError('Invalid as-of quote ordinal/time ordering')
    return data


def normalize_fit(x):
    x=np.asarray(x,dtype='float64')
    if not np.isfinite(x).all():raise ValueError('Nonfinite causal input')
    lo,hi=np.quantile(x,[.01,.99],axis=0)
    t=np.clip(x,lo,hi)
    mid=t.mean(axis=0);std=t.std(axis=0);std[std<1e-7]=1
    return lo,hi,mid,std


def transform(x,stats):
    lo,hi,mid,std=stats
    return ((np.clip(x,lo,hi)-mid)/std).astype('float32')


def fit_predict(xt,yt,xv,add_p5):
    # Identical original positions, original-policy outcomes, and tuning
    # for both baselines. Freeze one simple regularized linear predictor.
    if not add_p5:
        xt=xt[:,:-1];xv=xv[:,:-1]
    stats=normalize_fit(xt)
    # Winsorize TRAIN cash target only to avoid extrapolating one gapped
    # extreme event to all observations. Evaluate against UNCLIPPED losses.
    low,high=np.quantile(yt,[.001,.999])
    model=Ridge(alpha=500.,solver='lsqr',tol=1e-5)
    model.fit(transform(xt,stats),np.clip(yt,low,high))
    pred=model.predict(transform(xv,stats))
    fitted=model.predict(transform(xt,stats))
    return pred,fitted


def cvar_by_predicted_bucket(train_pred,train_delta,test_pred,levels=8):
    """Training-only conditional lower 5% HOLD-vs-EXIT tail loss estimate."""
    cuts=np.quantile(train_pred,np.linspace(0,1,levels+1)[1:-1])
    btrain=np.searchsorted(cuts,train_pred,side='right')
    btest=np.searchsorted(cuts,test_pred,side='right')
    out=np.empty(len(test_pred))
    n_buckets=[]
    for j in range(levels):
        vals=train_delta[btrain==j]
        if len(vals)<500:
            vals=train_delta
        cutoff=np.quantile(vals,.05)
        cvar=max(0.,float(-vals[vals<=cutoff].mean()))
        out[btest==j]=cvar
        n_buckets.append((len(vals),cvar))
    return out,n_buckets


def grouped_report(pred,y,age,entry_time,now,model_cvar):
    pgood=y>0
    d={
       'positions':int(len(y)),
       'mean_observed_original_hold_minus_now':float(y.mean()),
       'fraction_original_hold_beat_immediate_exit':float(pgood.mean()),
       'prediction_auc_for_original_hold_better':float(roc_auc_score(pgood,pred)),
       'prediction_mae_cash':float(mean_absolute_error(y,pred)),
       'predicted_mean_hold_advantage':float(pred.mean()),
       'p05_observed_hold_minus_exit_cash':float(np.quantile(y,.05)),
       'observed_bottom_5pct_hold_cash_loss':float(max(0.,-np.mean(np.sort(y)[:max(1,int(np.ceil(.05*len(y))))]))),
       'mean_quoted_liquidation_now_cash':float(now.mean()),
       'predicted_conditional_cvar95_cash':float(model_cvar.mean()),
       'mean_source_quote_age_seconds':age,
    }
    # An explicit SCENARIO for a risk-adjusted decision with eta=0.0,
    # not an on-policy optimization. Costs of lost rearm aren't identified
    # from original entry ledger and are intentionally not imputed.
    for lam in (0.,.1,.25):
        utility=pred-lam*model_cvar
        enabled=utility>0
        key=f'lambda_{lam:g}_eta_zero'
        d[key]={
            'fraction_shadow_q_hold_above_q_exit':float(enabled.mean()),
            'mean_observed_delta_among_shadow_hold_recommendations':float(y[enabled].mean()) if enabled.any() else None,
            'original_trade_survivor_selection_only':True,
            'no_occupancy_penalty_because_not_identifiable':True,
        }
    return d


def train_folds(cached:Path, output:Path, pred_dir=None):
    d=load_cache(cached)
    out=[]
    for age in (1,3):
        for eval_month in range(6,10):
            prior=[d[k][age] for k in range(5,eval_month)]
            test=d[eval_month][age]
            xtr=np.concatenate([z['X'] for z in prior]);ytr=np.concatenate([z['delta'] for z in prior]);
            Xte=test['X'];yte=test['delta'];
            orig_pred,orig_train=fit_predict(xtr,ytr,Xte,False)
            p5_pred,p5_train=fit_predict(xtr,ytr,Xte,True)
            if pred_dir is not None:
                pred_dir.mkdir(parents=True,exist_ok=True)
                np.savez_compressed(pred_dir/f'pred_{eval_month:02d}_{age}s.npz',
                     delta=yte, pred_context=orig_pred,pred_plus_p5=p5_pred,
                     entry_day=test['entry_time']//86_400_000,net_now=test['now'])
            orig_cvar,_=cvar_by_predicted_bucket(orig_train,ytr,orig_pred)
            p5_cvar,_=cvar_by_predicted_bucket(p5_train,ytr,p5_pred)
            a=grouped_report(orig_pred,yte,age,test['entry_time'],test['now'],orig_cvar)
            b=grouped_report(p5_pred,yte,age,test['entry_time'],test['now'],p5_cvar)
            out.append(dict(landmark_seconds=age,eval_month=f'{eval_month:02d}',
                    train_months=[f'{i:02d}' for i in range(5,eval_month)],
                    train_landmark_positions=int(len(ytr)),
                    quote_context_only=a,quote_context_plus_frozen_p5=b,
                    incremental_p5_auc=float(b['prediction_auc_for_original_hold_better']-a['prediction_auc_for_original_hold_better']),
                    incremental_p5_mae_cash=float(b['prediction_mae_cash']-a['prediction_mae_cash']),
                    intrinsic_original_survivor_bias=True))
            print(f'age {age}s eval {eval_month:02d}: n={len(yte):,}, hold-minus-exit={yte.mean():+.5f}, '+
                  f'AUC context={a["prediction_auc_for_original_hold_better"]:.5f} '+
                  f'+P5={b["prediction_auc_for_original_hold_better"]:.5f}, '+
                  f'conditional CVaR={b["predicted_conditional_cvar95_cash"]:.4f}',flush=True)
    summary={}
    for age in (1,3):
        sub=[z for z in out if z['landmark_seconds']==age]
        summary[f'{age}s']={
            'total_evaluation_landmarks':sum(z['quote_context_only']['positions'] for z in sub),
            'equal_month_mean_hold_better_auc_context':float(np.mean([z['quote_context_only']['prediction_auc_for_original_hold_better'] for z in sub])),
            'equal_month_mean_hold_better_auc_context_plus_frozen_p5':float(np.mean([z['quote_context_plus_frozen_p5']['prediction_auc_for_original_hold_better'] for z in sub])),
            'equal_month_mean_incremental_p5_auc':float(np.mean([z['incremental_p5_auc'] for z in sub])),
            'equal_month_mean_incremental_p5_mae_cash':float(np.mean([z['incremental_p5_mae_cash'] for z in sub])),
            'equal_month_mean_observed_hold_cash_advantage':float(np.mean([z['quote_context_only']['mean_observed_original_hold_minus_now'] for z in sub])),
        }
    result=dict(classification='ORIGINAL_POLICY_SURVIVOR_CONDITIONAL_HOLD_CASH_NOT_ON_POLICY_OPTIMAL_STOP',
            model='frozen 155-feature entry-time LightGBM p5 + earlier-fold regularized ridge cash continuation',
            model_parameters={'ridge_alpha':500,'target_winsor_train_quantiles':[.001,.999],'features':FEATURE_NAMES},
            train_months='May through previous evaluation month, all original primary scores originally held-out by month',
            evaluation_months='June through September 2026, prior research exposed',
            cost_assumptions={'K':1.,'C':.2,'C_cancels_in_delta_hold_minus_exit':True},
            policy_execution_not_simulated=True,
            account_governor_not_simulated=True,
            causal_quote_observations_and_original_exit_only=True,
            occupancy_cost_not_observable_from_original_ledger=True,
            summary=summary,folds=out)
    output.write_text(json.dumps(result,indent=2)+'\n',encoding='utf-8')
    return result


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--cache-dir',type=Path,required=True)
    p.add_argument('--output',type=Path,required=True)
    p.add_argument('--pred-dir',type=Path)
    a=p.parse_args();train_folds(a.cache_dir,a.output,a.pred_dir)
if __name__=='__main__':main()
